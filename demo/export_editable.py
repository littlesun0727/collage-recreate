"""Export native editable tasks without machine paths or service credentials.

The viewer's existing content-addressed media are reused. Run on the source
Windows machine; restore_editor.py materializes normal tasks on either OS.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
from functools import lru_cache

ROOT = Path(__file__).resolve().parent
SECRET = {'api_key', 'apikey', 'key_file', 'credentials', 'authorization',
          'headers', 'access_token', 'refresh_token', 'password', 'secret'}
ABSOLUTE = re.compile(r'^[a-zA-Z]:[/\\]')


def read(p):
    return json.loads(p.read_text(encoding='utf-8-sig'))


@lru_cache(maxsize=None)
def sha(p):
    with p.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


def encode(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + '\n').encode('utf-8')


class Export:
    def __init__(self, model):
        self.model = model.resolve()
        self.blobs = {}
        self.added = 0

    def blob(self, p):
        digest = sha(p)
        target = ROOT/'data'/digest
        if not target.exists():
            shutil.copyfile(p, target)
            self.added += p.stat().st_size
        record = {'file': 'data/'+digest, 'sha256': digest, 'bytes': p.stat().st_size}
        self.blobs[digest] = record
        return digest

    def task(self, run):
        run = run.resolve()
        mapping = {}
        files = {}
        visiting = set()

        def target(p):
            p = p.resolve()
            if p.is_relative_to(run):
                return p.relative_to(run).as_posix()
            return 'originals/'+sha(p)[:16]+'/'+p.name

        def add(p):
            p = p.resolve()
            if p == self.model:
                return '@MODEL@'
            if p.suffix.lower() in {'.ttf', '.ttc', '.otf'}:
                return p.name  # Use system fonts or the bundled open font at runtime.
            if p in mapping:
                return '@RUN@/'+mapping[p]
            relative = target(p)
            mapping[p] = relative
            if p.suffix == '.json':
                visiting.add(p)
                value = read(p)
                if relative == 'sdk-timing.json':
                    value = {k: v for k, v in value.items() if k in {
                        'model', 'effort', 'started_at', 'finished_at', 'elapsed_seconds', 'status'}}
                if relative == 'reveal-config.json':
                    value = {k: v for k, v in value.items() if k in {'enabled', 'padding', 'batch_size'}}
                    value['offline'] = True
                if relative == 'result.json':
                    value.pop('editor_layers', None)  # Disposable exports, regenerated by the existing editor.
                files[relative] = {'json': clean(value)}
                visiting.remove(p)
            elif p.suffix == '.jsonl':
                rows = []
                for line in p.read_text(encoding='utf-8', errors='replace').splitlines():
                    try:
                        rows.append(clean(json.loads(line)))
                    except ValueError:
                        continue
                files[relative] = {'jsonl': rows}
            else:
                files[relative] = {'blob': self.blob(p)}
            return '@RUN@/'+relative

        def clean(value):
            if isinstance(value, dict):
                # Verify pinned originals before changing paths or serializing them.
                if value.get('file') and value.get('sha256'):
                    original = Path(value['file'])
                    if original.is_file() and sha(original) != value['sha256']:
                        frozen = ROOT/'data'/value['sha256']
                        if frozen.is_file() and sha(frozen) == value['sha256']:
                            relative = 'preserved/'+value['sha256']+original.suffix.lower()
                            files[relative] = {'blob': self.blob(frozen)}
                            value = dict(value, file='@RUN@/'+relative)
                        else:
                            # Historical receipts can point at a subsequently replaced tile.
                            # Immutable version evidence remains independently hash checked.
                            pass
                return {k: clean(v) for k, v in value.items() if k.lower() not in SECRET}
            if isinstance(value, list):
                return [clean(v) for v in value]
            if isinstance(value, str) and ABSOLUTE.match(value):
                p = Path(value)
                if p.is_file():
                    return add(p)
                if p.is_relative_to(run):
                    return '@RUN@/'+p.relative_to(run).as_posix()
                return '@RUN@/originals' if p.is_dir() else '[source machine path omitted]'
            if isinstance(value, str):
                # Diagnostics sometimes contain paths inside an explanatory sentence.
                return re.sub(r'[a-zA-Z]:[\\/][^\s"\n]+', '[source machine path omitted]', value)
            return value

        for p in sorted(run.rglob('*')):
            if not p.is_file():
                continue
            parts = p.relative_to(run).parts
            motion_version = len(parts) == 5 and parts[:3] == ('chat', 'motion', 'versions') and p.name in {'result.json', 'progress.json'}
            if (parts[0] in {'chat', 'editor_layers'} and not motion_version) or p.suffix in {'.tmp', '.lock'}:
                continue
            if parts[0] == 'observability' and parts[1] not in {'versions', 'operations', 'checkpoints'}:
                continue
            if p.name == '.write.lock':
                continue
            add(p)
        identifier = hashlib.sha256(str(run).encode()).hexdigest()[:16]
        task = {'id': identifier, 'name': run.name, 'files': files}
        destination = ROOT/'editable/tasks'/(identifier+'.json')
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(encode(task))
        return {'id': identifier, 'name': run.name, 'template': destination.relative_to(ROOT).as_posix(),
                'sha256': sha(destination), 'files': len(files)}

    def model_parts(self):
        folder = ROOT/'editable/model'
        folder.mkdir(parents=True, exist_ok=True)
        parts = []
        with self.model.open('rb') as f:
            while block := f.read(48*1024*1024):
                p = folder/('birefnet-'+str(len(parts))+'.part')
                p.write_bytes(block)
                parts.append({'file': p.relative_to(ROOT).as_posix(), 'sha256': sha(p), 'bytes': len(block)})
        return {'name': self.model.name, 'sha256': sha(self.model), 'bytes': self.model.stat().st_size, 'parts': parts}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--tasks', type=Path, required=True)
    parser.add_argument('--model', type=Path, required=True)
    args = parser.parse_args()
    export = Export(args.model)
    manifest = {'schema': 'collage-native-migration-v1', 'tasks': [], 'model': export.model_parts()}
    for p in sorted(args.tasks.glob('*/input.json')):
        if not (p.parent/'scene.json').exists():
            continue
        task = export.task(p.parent)
        manifest['tasks'].append(task)
        print(task['name'], task['files'], flush=True)
    manifest['blobs'] = export.blobs
    manifest['default_task'] = 'b85eec1d0ef5933e'
    (ROOT/'editable/manifest.json').write_bytes(encode(manifest))
    print(json.dumps({'tasks': len(manifest['tasks']), 'blobs': len(export.blobs),
                      'added_mib': round(export.added/2**20, 1)}), flush=True)


if __name__ == '__main__':
    main()
